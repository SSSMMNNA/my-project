export function getUpcomingEvents(count = 15): EconomicEvent[] {
  const now = new Date()
  return ECONOMIC_EVENTS
    .filter(e => new Date(e.datetimeJST) >= now)
    .sort((a, b) => new Date(a.datetimeJST).getTime() - new Date(b.datetimeJST).getTime())
    .slice(0, count)
}

